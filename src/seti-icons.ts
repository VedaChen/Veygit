/** 按文件路径取 seti 图标 class；未知类型返回空串（调用方可回退 codicon-file） */
export function fileIconClass(path: string): string {
  const { name } = splitPath(path);
  const lower = name.toLowerCase();
  const byName = fileNameToIconClass[lower];
  if (byName) {
    return byName;
  }
  const dot = lower.lastIndexOf('.');
  if (dot >= 0) {
    const byExt = extToIconClass[lower.slice(dot + 1)];
    if (byExt) {
      return byExt;
    }
  }
  return '';
}
